#!/usr/bin/env python3
"""Adds `imported_at` to every table of every collector schema (DATA-01, approved 12 November 2026).

    python docs/tools/generate_imported_at.py            write the block into each Collector/*/sql/schema.sql, and the standalone migration files
    python docs/tools/generate_imported_at.py --check    say what is out of date, change nothing (exit code 1 if anything is)

`imported_at` is when a row was WRITTEN to the database. `captured_at`, where a table has one, is when the source data was captured: they differ.
Rows stored before the column was added are left empty on purpose (nobody knows when they were imported); every row stored from then on gets the
time it was inserted, with no change to the loaders, which name their columns when they insert. The statements are safe to run again, and do not
touch any existing row. The block sits after the last table and before the first view, so views written as `SELECT t.*` pick the column up the
next time they are re-created. A test (backend/api/test_schema_sql.py) keeps every table covered, so a table added later fails it until this is re-run."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
COLLECTORS = [('Collector/AutotaskLight-main', 'autotask'), ('Collector/ncentralAPI-main', 'ncentral'),
              ('Collector/SentinelOne-main', 'sentinelone'), ('Collector/Cove-main', 'cove')]
MIGRATION = 'sql/migrations/2026-11-12_imported_at.sql'
BEGIN_PREFIX = '-- BEGIN imported_at'   # the block is found by this, whatever follows it, so a changed heading replaces the block and never adds a second
BEGIN = BEGIN_PREFIX + ' (DATA-01, approved 12 Nov 2026)'
END = '-- END imported_at'
VIEW = re.compile(r'^\s*(CREATE\s+OR\s+REPLACE\s+VIEW|CREATE\s+VIEW|DROP\s+VIEW)\b', re.I)


def tables_of(sql):
    return re.findall(r'^\s*CREATE TABLE IF NOT EXISTS\s+(\w+)', sql, re.M | re.I)


def block(tables):
    lines = [BEGIN + ': generated by docs/tools/generate_imported_at.py, do not edit by hand.',
             '-- imported_at is when a row was written to this database. captured_at, where a table has one, is when the source data was captured.',
             '-- Rows stored before this existed are left empty (NULL) on purpose: nobody knows when they were imported. Every row stored from now on',
             '-- gets the time it was inserted, with no change to the loaders (they name their columns). Safe to run again; no existing row is touched.']
    for table in tables:
        lines += [f'ALTER TABLE {table} ADD COLUMN IF NOT EXISTS imported_at TIMESTAMPTZ;', f'ALTER TABLE {table} ALTER COLUMN imported_at SET DEFAULT now();']
    return '\n'.join(lines + [END]) + '\n'


def insert_block(sql, text):
    """The schema with the block in place: replaced where it already is, otherwise just before the comment above the first view."""
    if BEGIN_PREFIX in sql:
        start = sql.index(BEGIN_PREFIX)
        end = sql.index(END, start) + len(END)
        end = end + 1 if sql[end:end + 1] == '\n' else end
        return sql[:start] + text + sql[end:]
    lines = sql.splitlines(keepends=True)
    first = next((i for i, line in enumerate(lines) if VIEW.match(line)), None)
    if first is None:
        return sql.rstrip('\n') + '\n\n' + text
    while first > 0 and (lines[first - 1].lstrip().startswith('--') or not lines[first - 1].strip()):
        first -= 1
    return ''.join(lines[:first]) + '\n' + text + '\n' + ''.join(lines[first:])


def migration(schema, text):
    return (f'-- DATA-01: record when each row was imported (generated by docs/tools/generate_imported_at.py; the same block is in schema.sql).\n'
            f'-- Run once on an existing database, at a time when no collector is running (each ALTER takes a very short lock):\n'
            f'--     psql "<your connection string>" -f sql/migrations/2026-11-12_imported_at.sql\n'
            f'-- It is safe to run again. It does not change any existing row.\n'
            f'BEGIN;\nSET LOCAL search_path TO {schema}, public;\n\n{text}\nCOMMIT;\n')


def render_all():
    files = {}
    for folder, schema in COLLECTORS:
        schema_path = f'{folder}/sql/schema.sql'
        sql = (ROOT / schema_path).read_text(encoding='utf-8')
        text = block(tables_of(sql))
        files[schema_path] = insert_block(sql, text)
        files[f'{folder}/{MIGRATION}'] = migration(schema, text)
    return files


def main():
    files = render_all()
    stale = [p for p, text in files.items() if not (ROOT / p).is_file() or (ROOT / p).read_text(encoding='utf-8') != text]
    if '--check' in sys.argv:
        print('up to date' if not stale else 'out of date: ' + ', '.join(stale))
        return 1 if stale else 0
    for p in stale:
        (ROOT / p).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / p).write_text(files[p], encoding='utf-8', newline='\n')
        print('wrote', p)
    return 0


if __name__ == '__main__':
    sys.exit(main())
