#!/usr/bin/env python3
"""Regenerates docs/SOURCE_INDEX.md: every module in the project with the first line of its docstring or comment.

    python docs/tools/generate_source_index.py          write it
    python docs/tools/generate_source_index.py --check  exit 1 if it is out of date

`backend/api/test_docs.py` runs the check, so a new module cannot be added without the index being regenerated."""
import ast
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SKIP = {'node_modules', '__pycache__', '.venv', 'dist', 'vendor'}

PROVENANCE = '''## Provenance

PROVENANCE_TEXT'''


def first_line(path):
    text = path.read_text(encoding='utf-8', errors='replace')
    if path.suffix == '.py':
        try:
            doc = ast.get_docstring(ast.parse(text))
            if doc:
                return doc.strip().splitlines()[0]
        except SyntaxError:
            pass
        return ''
    pattern = r'\s*rem\s+(.+)' if path.suffix == '.cmd' else r'\s*//\s*(.+)'
    m = re.match(pattern, text, re.I)
    return m.group(1).strip() if m else ''


def listing(root, extensions):
    lines = []
    for folder, dirs, files in os.walk(ROOT / root):
        dirs[:] = sorted(d for d in dirs if d not in SKIP)
        for name in sorted(files):
            if name.endswith(extensions):
                path = Path(folder) / name
                note = first_line(path)
                lines.append(f'- `{path.relative_to(ROOT).as_posix()}`' + (f' — {note}' if note else ''))
    return lines


def render():
    lines = ['# Source index and provenance', '',
             'Paths are relative to the project folder (`ops-dashboard/`). The first line of each module\'s docstring or comment is shown where it has one. '
             'Generated by `docs/tools/generate_source_index.py` from the tree that ships with this pack (a test fails if it is out of date); it does not assert that a deployed server matches.',
             '', '## Backend', '', *listing('backend', ('.py',)), '', '## Frontend', '', *listing('frontend/src', ('.js', '.jsx')), '', '## Collectors', '']
    for folder in sorted(os.listdir(ROOT / 'Collector')):
        base = ROOT / 'Collector' / folder
        files = sorted(f for f in os.listdir(base) if f.endswith(('.py', '.ps1', '.md')))
        lines.append(f'- `Collector/{folder}/` — ' + ', '.join(f'`{f}`' for f in files) + ('; `sql/` (schema and queries)' if (base / 'sql').is_dir() else ''))
    lines += ['', '## Documentation tooling', '']
    for name in ('serve.py', 'Open-Docs.cmd', 'tools/generate_er.py', 'tools/generate_fixtures.py', 'tools/generate_source_index.py', 'tools/viewer_smoke.js'):
        path = ROOT / 'docs' / name
        note = first_line(path)
        lines.append(f'- `docs/{name}`' + (f' — {note}' if note else ''))
    return '\n'.join(lines) + '\n\n' + PROVENANCE.replace('PROVENANCE_TEXT', (ROOT / 'docs' / 'tools' / 'provenance.txt').read_text(encoding='utf-8').strip()) + '\n'


def main():
    text = render()
    target = ROOT / 'docs' / 'SOURCE_INDEX.md'
    if '--check' in sys.argv:
        fresh = target.is_file() and target.read_text(encoding='utf-8') == text
        print('up to date' if fresh else 'STALE: run python docs/tools/generate_source_index.py')
        sys.exit(0 if fresh else 1)
    target.write_text(text, encoding='utf-8')
    print(f'wrote {target.relative_to(ROOT)} ({text.count(chr(10))} lines)')


if __name__ == '__main__':
    main()
